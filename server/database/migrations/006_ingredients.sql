-- The ingredient table (#147): what an ingredient is, matched by name, and how
-- heavy a millilitre of it is. Until now it was a file checked in beside the
-- matcher (#132); from here on it lives here, and learns from the recipes
-- people save. The 420 entries the file held are inserted at the end, once.
-- A wrong seeded name or density is corrected by a later migration.
--
-- Normalization never queries these tables: it matches against a snapshot of
-- ingredients and ingredient_names held in memory, reloaded by the resolver.

-- Trigram search over FoodData Central, and edit distance between names.
-- In public, where every connection's search_path finds them.
CREATE EXTENSION IF NOT EXISTS pg_trgm WITH SCHEMA public;
CREATE EXTENSION IF NOT EXISTS fuzzystrmatch WITH SCHEMA public;

CREATE TABLE ingredients (
    -- What a stored recipe's food.key points at, so it is never renamed.
    key TEXT PRIMARY KEY CHECK (key ~ '^[a-z0-9_]+$'),
    -- The FoodData Central food the density was read from: its id, its own
    -- description and the portion used. Null for a food FDC lacks, and for a
    -- learned key with no clear FDC match.
    fdc_id INTEGER,
    fdc TEXT,
    -- Grams for a solid, millilitres for a liquid. Null for a learned key: a
    -- weight still converts to grams and a volume to millilitres, never across.
    form TEXT CHECK (form IN ('solid', 'liquid')),
    portion TEXT,
    grams_per_ml DOUBLE PRECISION CHECK (grams_per_ml > 0),
    -- When the resolver made it from sightings; null for a seeded key. Only
    -- learned keys are checked for similar ones.
    learned_at TIMESTAMPTZ,

    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    CHECK (learned_at IS NOT NULL OR form IS NOT NULL),
    CHECK (grams_per_ml IS NULL OR fdc_id IS NOT NULL)
);

-- Every name a key is matched by, as written ("All-Purpose Flour"); the
-- matcher compares them lower case, without accents or punctuation. The first
-- in each language is the one shown (#139).
CREATE TABLE ingredient_names (
    name TEXT NOT NULL CHECK (name <> ''),
    lang TEXT NOT NULL CHECK (lang IN ('en', 'de')),
    key TEXT NOT NULL REFERENCES ingredients (key),
    position SMALLINT NOT NULL CHECK (position >= 0),

    PRIMARY KEY (lang, name),
    UNIQUE (key, lang, position)
);

-- A name a saved recipe used that matched nothing: written with the recipe, in
-- its transaction, by every save, edit, progression and variant. Kept when the
-- recipe is edited or deleted, so a count is of cooks who ever saved the name.
-- One row per recipe, owner and name, however often it is saved.
CREATE TABLE ingredient_sightings (
    -- As the matcher compares it, with leading numbers, units and describing
    -- words dropped: "2 EL Gochujang" and "gochujang (scharf)" are "gochujang".
    name TEXT NOT NULL CHECK (name <> ''),
    lang TEXT NOT NULL CHECK (lang IN ('en', 'de')),
    owner_sub TEXT NOT NULL,
    recipe_id UUID REFERENCES recipes (id) ON DELETE SET NULL,

    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    UNIQUE (recipe_id, owner_sub, name, lang)
);
CREATE INDEX ingredient_sightings_name_idx ON ingredient_sightings (name);

-- A cook's answer to "which ingredient is this?" (#133): chosen for a key, or
-- rejected for one. A null key is "don't ask again", and no vote.
CREATE TABLE ingredient_alias_votes (
    owner_sub TEXT NOT NULL,
    -- Lower case, as the matcher compares it.
    name TEXT NOT NULL CHECK (name <> ''),
    lang TEXT NOT NULL CHECK (lang ~ '^[a-z]{2}$'),
    key TEXT REFERENCES ingredients (key),
    chosen BOOLEAN NOT NULL,

    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    UNIQUE NULLS NOT DISTINCT (owner_sub, name, lang, key)
);

-- Two active keys that may be one food. Changes nothing; a curator decides
-- (#148). A pair is stored once, in key order, and once per reason it was
-- flagged for.
CREATE TABLE ingredient_flags (
    a TEXT NOT NULL REFERENCES ingredients (key),
    b TEXT NOT NULL REFERENCES ingredients (key),
    -- trailing: one key's name is the other's plus words after it.
    -- edit: two names within an edit distance of 2 (1 under six letters).
    -- fdc: both have the same FDC food.
    reason TEXT NOT NULL CHECK (reason IN ('trailing', 'edit', 'fdc')),

    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    PRIMARY KEY (a, b, reason),
    CHECK (a < b)
);

-- Cooks who opted out of shared ingredient data ("Contribute to shared
-- ingredient data" in shared/utils/preferences.ts). Their sightings and votes
-- are left out of every count below, past ones included.
CREATE VIEW ingredient_opted_out AS
    SELECT owner_sub FROM preferences WHERE settings->>'sharedIngredients' = 'off';

-- How many cooks have used each unmatched name, in any language, and in which
-- languages. Thresholds are the app's configuration, so the resolver compares
-- the count; a view can't read it.
CREATE VIEW ingredient_sighting_counts AS
    SELECT s.name,
           count(DISTINCT s.owner_sub)::int AS cooks,
           array_agg(DISTINCT s.lang ORDER BY s.lang) AS langs
    FROM ingredient_sightings s
    WHERE s.owner_sub NOT IN (SELECT owner_sub FROM ingredient_opted_out)
    GROUP BY s.name;

-- How many cooks chose or rejected each key for a name (#133).
CREATE VIEW ingredient_alias_counts AS
    SELECT v.name, v.lang, v.key,
           count(*) FILTER (WHERE v.chosen)::int AS chosen,
           count(*) FILTER (WHERE NOT v.chosen)::int AS rejected
    FROM ingredient_alias_votes v
    WHERE v.key IS NOT NULL
      AND v.owner_sub NOT IN (SELECT owner_sub FROM ingredient_opted_out)
    GROUP BY v.name, v.lang, v.key;

-- FoodData Central, SR Legacy and Foundation Foods, loaded by
-- scripts/ingredients.ts and replaced whole on every run. Only what a density
-- needs: a food's description, and its cup and spoon portions. Empty until
-- the script has run, and the resolver works without it.
CREATE TABLE fdc_foods (
    fdc_id INTEGER PRIMARY KEY,
    data_type TEXT NOT NULL CHECK (data_type IN ('sr_legacy_food', 'foundation_food')),
    description TEXT NOT NULL
);
CREATE INDEX fdc_foods_description_trgm_idx ON fdc_foods USING gin (lower(description) gin_trgm_ops);

CREATE TABLE fdc_portions (
    fdc_id INTEGER NOT NULL REFERENCES fdc_foods (fdc_id) ON DELETE CASCADE,
    amount DOUBLE PRECISION NOT NULL CHECK (amount > 0),
    unit TEXT NOT NULL CHECK (unit IN ('cup', 'tbsp', 'tsp', 'fl oz')),
    -- FDC's own words for it ("cup, chopped"), as the portion is shown.
    modifier TEXT NOT NULL,
    grams DOUBLE PRECISION NOT NULL CHECK (grams > 0)
);
CREATE INDEX fdc_portions_fdc_id_idx ON fdc_portions (fdc_id);

-- Re-normalizing stored recipes after a key is learned is not an edit: it
-- sets recipeat.renormalizing for its own transaction, and updated_at keeps
-- saying when the cook last changed the recipe.
CREATE OR REPLACE FUNCTION recipes_touch_updated_at() RETURNS trigger AS $$
BEGIN
    IF current_setting('recipeat.renormalizing', true) IS DISTINCT FROM 'on' THEN
        NEW.updated_at := now();
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

